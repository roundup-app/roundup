import { expect, it } from "vitest";
import type { ChangedFile } from "@contracts/agent/ChangedFile";
import { groupModules, hunkFunction, isTest, moduleOf, noiseOf, TOP_LEVEL } from "./modules";

const file = (path: string, counts: { added: number; removed: number } | null = null): ChangedFile => ({ path, status: "modified", line: 1, counts, blob: null });

it("u7678b_a_files_module_comes_from_its_path_alone", () => {
  expect(moduleOf("crates/x/src/b.rs")).toBe("crates/x");
  expect(moduleOf("crates/x/tests/a.rs")).toBe("crates/x");
  expect(moduleOf("apps/desktop/src/changes/A.tsx")).toBe("apps/desktop/src/changes");
  expect(moduleOf("apps/desktop/src/changes/A.test.tsx")).toBe("apps/desktop/src/changes");
  expect(moduleOf("src/lib/a.ts")).toBe(TOP_LEVEL);
  expect(moduleOf("README.md")).toBe(TOP_LEVEL);
});

it("u7678b_a_test_is_told_from_logic_by_its_path", () => {
  for (const path of ["a/tests/x.rs", "a/__tests__/x.ts", "a/A.test.tsx", "a/b.spec.ts", "a/foo_test.go", "a/foo_spec.rb", "a/test_foo.py"]) expect(isTest(path), path).toBe(true);

  for (const path of ["a/src/x.rs", "a/contest.ts", "a/latest.ts", "a/testing.ts"]) expect(isTest(path), path).toBe(false);
});

it("u7678b_lockfiles_and_generated_files_are_noise", () => {
  for (const path of ["go.sum", "a/bun.lockb", "Cargo.lock", "package-lock.json", "pnpm-lock.yaml"]) expect(noiseOf(path), path).toBe("lockfile");

  for (const path of ["a/generated/x.ts", "a/__generated__/x.ts", "a/autogenerated/x", "a/x.generated.ts", "a/x.min.js", "a/x.min.css"]) expect(noiseOf(path), path).toBe("generated");
  expect(noiseOf("a/src/x.ts")).toBeUndefined();
});

it("u7678a_the_list_groups_files_by_module_with_summed_counts", () => {
  const { modules, noise } = groupModules([
    file("crates/x/tests/a.rs", { added: 1, removed: 1 }), file("crates/x/src/b.rs", { added: 4, removed: 2 }), file("crates/x/src/c.rs"),
    file("README.md"), file("crates/x/generated/g.rs"), file("Cargo.lock"), file("pnpm-lock.yaml"),
  ]);

  expect(modules.map(each => each.name)).toEqual(["crates/x", "Top level"]);
  const x = modules.find(each => each.name === "crates/x");

  expect([x?.files.length, x?.added, x?.removed]).toEqual([3, 5, 3]);
  expect(x?.files.map(each => each.path)).toEqual(["crates/x/src/b.rs", "crates/x/src/c.rs", "crates/x/tests/a.rs"]);
  expect(modules.find(each => each.name === TOP_LEVEL)?.counted).toBe(false);
  expect(noise.map(each => [each.kind, each.files.length])).toEqual([["generated", 1], ["lockfile", 2]]);
});

it("u7678c_each_hunk_header_names_its_file_and_function", () => {
  const lines = ["import a", "export const f = () => {", "  body", "  more", "}"];

  expect(hunkFunction(lines, 4)).toBe("export const f = () => {");
  expect(hunkFunction(lines, 1)).toBeUndefined();
  expect(hunkFunction(["x".repeat(100)], 2)?.length).toBe(80);
});
