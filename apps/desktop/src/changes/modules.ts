import type { ChangedFile } from "@contracts/agent/ChangedFile";
import { copy } from "./copy";

/** U7678b: the name of the module a file with no directory left belongs to. */
export const TOP_LEVEL = copy.topLevel;

const SOURCE_ROOTS = new Set(["src", "lib", "test", "tests", "__tests__", "spec"]);

const TEST_DIRECTORIES = new Set(["test", "tests", "__tests__", "spec"]);

const GENERATED_DIRECTORIES = new Set(["generated", "__generated__", "autogenerated"]);

const nameOf = (path: string) => path.split("/").at(-1) ?? path;

const directoriesOf = (path: string) => path.split("/").slice(0, -1);

/** U7678b: a file's module, from its path alone: its directory without trailing source and test segments. */
export const moduleOf = (path: string): string => {
  const directories = directoriesOf(path);

  while (directories.length > 0 && SOURCE_ROOTS.has(directories.at(-1) ?? "")) directories.pop();

  return directories.join("/") || TOP_LEVEL;
};

/** U7678b: a test by its path; #7679's Logic and Tests lenses read this and no copy. */
export const isTest = (path: string): boolean => {
  const base = nameOf(path);
  const stem = base.replace(/\.[^.]*$/, "");

  return directoriesOf(path).some(each => TEST_DIRECTORIES.has(each)) || base.includes(".test.") || base.includes(".spec.") || /_(test|spec)$/.test(stem) || base.startsWith("test_");
};

export type NoiseKind = "generated" | "lockfile";

const GENERATED: NoiseKind = "generated";

const LOCKFILE: NoiseKind = "lockfile";

/** U7678b: a lockfile or a generated file by its path, else `undefined`. */
export const noiseOf = (path: string): NoiseKind | undefined => {
  const base = nameOf(path);

  if (base === "go.sum" || base === "bun.lockb" || base.endsWith(".lock") || base.endsWith("-lock.json") || base.endsWith("-lock.yaml")) return LOCKFILE;

  if (directoriesOf(path).some(each => GENERATED_DIRECTORIES.has(each)) || base.includes(".generated.") || base.endsWith(".min.js") || base.endsWith(".min.css")) return GENERATED;

  return undefined;
};

/** `total` is the files the row counts; a find (U7679d) narrows `files` and leaves it. */
export type ModuleGroup = { name: string; files: ChangedFile[]; total: number; added: number; removed: number; counted: boolean };

export type Grouped = { modules: ModuleGroup[]; noise: { kind: NoiseKind; files: ChangedFile[]; total: number }[] };

const byPath = (a: ChangedFile, b: ChangedFile) => a.path.localeCompare(b.path, undefined, { numeric: true, sensitivity: "base" });

/** U7678a, U7678c: files in the order a module's scroll reads them: logic in path order, then tests in path order. */
export const scrollOrder = (files: readonly ChangedFile[]): ChangedFile[] => [...files.filter(file => !isTest(file.path)).sort(byPath), ...files.filter(file => isTest(file.path)).sort(byPath)];

/** U7678a, U7678b: the list's modules in path order with summed counts, and a noise row for each kind the change holds. */
export const groupModules = (files: readonly ChangedFile[]): Grouped => {
  const modules = new Map<string, ChangedFile[]>();
  const noise = new Map<NoiseKind, ChangedFile[]>();

  const add = <K>(bucket: Map<K, ChangedFile[]>, key: K, file: ChangedFile) => bucket.set(key, [...bucket.get(key) ?? [], file]);

  for (const file of files) {
    const kind = noiseOf(file.path);

    if (kind) add(noise, kind, file); else add(modules, moduleOf(file.path), file);
  }

  return {
    modules: [...modules].sort(([a], [b]) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" })).map(([name, list]) => ({
      name,
      files: scrollOrder(list),
      total: list.length,
      added: list.reduce((sum, file) => sum + (file.counts?.added ?? 0), 0),
      removed: list.reduce((sum, file) => sum + (file.counts?.removed ?? 0), 0),
      counted: list.some(file => file.counts !== null),
    })),
    noise: (["generated", "lockfile"] as const).flatMap(kind => noise.has(kind) ? [{ kind, files: [...noise.get(kind) ?? []].sort(byPath), total: noise.get(kind)?.length ?? 0 }] : []),
  };
};

/** U7678c: the function git's default hunk header names: the nearest line above `line` (1-based) starting with a letter, `_` or `$`, cut to 80 characters. */
export const hunkFunction = (lines: readonly string[], line: number): string | undefined => {
  for (let at = Math.min(line - 1, lines.length) - 1; at >= 0; at--) {
    const text = lines[at] ?? "";

    if (/^[A-Za-z_$]/.test(text)) return text.slice(0, 80).trimEnd();
  }

  return undefined;
};
