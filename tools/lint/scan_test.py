"""T3797a observers: real tools in isolated tracked repositories, no application processes."""
import json
from pathlib import Path
import subprocess
import shutil
import sys
import tempfile
import unittest

HERE = Path(__file__).resolve().parent
EMPTY = {key: [] for key in ('size', 'ast', 'typos', 'ruff', 'dependencies')}


class Lints(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix='lint-fixture-')
        self.root = Path(self.directory.name)
        self.git('init', '-q')
        self.git('config', 'user.email', 'lint@example.invalid')
        self.git('config', 'user.name', 'Lint fixture')
        self.write('tools/lint/debt.json', json.dumps(EMPTY))
        self.commit()

    def tearDown(self):
        self.directory.cleanup()

    def git(self, *args):
        return subprocess.run(['git', *args], cwd=self.root, check=True, capture_output=True, text=True).stdout

    def write(self, path, text):
        file = self.root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text)
        self.git('add', path)

    def commit(self):
        self.git('-c', 'core.hooksPath=/dev/null', 'commit', '-qm', 'Fixture')

    def scan(self, section, status, *args):
        result = subprocess.run([sys.executable, HERE / 'scan.py', section, '--root', self.root, '--base', 'HEAD', *args],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, status, result.stdout + result.stderr)
        return result.stdout + result.stderr

    def baseline(self, section):
        result = self.scan(section, 0, '--record')
        # stderr's tool identity follows stdout; parse only the JSON document.
        rows = json.JSONDecoder().raw_decode(result)[0][section]
        debt = json.loads((self.root / 'tools/lint/debt.json').read_text())
        debt[section] = [dict(row, reason=row.get('reason', 'Existing fixture occurrence')) for row in rows]
        self.write('tools/lint/debt.json', json.dumps(debt))
        self.commit()
        return debt

    def test_t3797a_size_cap(self):
        for path, count, status in [('exact.unusual', 1000, 0), ('large.unusual', 1001, 1)]:
            with self.subTest(path=path):
                self.write(path, 'x\n' * count)
                output = self.scan('size', status)
                if status:
                    self.assertIn(path, output)
                    self.assertIn('1001', output)

    def test_t3797a_size_cap_generated_predicate(self):
        for path, prefix in [('vendor/local.txt', ''), ('a.lock.backup', ''), ('x-lock.json', ''),
                             ('Package.resolved', ''), ('code.any', '// @generated\n'),
                             ('header.any', '\n\n\n\nCode generated by test DO NOT EDIT\n'),
                             ('binary.any', '\0'), ('attrb.any', ''), ('attr.any', '')]:
            self.write(path, prefix + 'x\n' * 1001)
        self.write('.gitattributes', 'attr.any linguist-generated=true\nattrb.any -diff\n')
        self.scan('size', 0)

    def test_t3797a_size_cap_checks_revision_attributes(self):
        self.write('ordinary', 'x\n' * 1001)
        self.write('.gitattributes', 'ordinary linguist-vendored\n')
        self.commit()
        self.write('.gitattributes', '')
        self.assertIn('ordinary', self.scan('size', 1))

    def test_t3797a_sleep_polling(self):
        for source, status in [
            ('async fn f() { loop { tokio::time::sleep(x).await; } }', 1),
            ('fn f() { while ready() { std::thread::sleep(x); } }', 1),
            ('async fn f() { for i in items { sleep_until(x).await; } }', 1),
            ('async fn f() { while ready() { clock.sleep_until(x).await; } }', 1),
            ('fn f() { sleep(x); let s = "loop { sleep(x); }"; /* loop { sleep(x); } */ }', 0),
        ]:
            with self.subTest(source=source):
                self.write('test.rs', source)
                self.scan('ast', status)

    def test_t3797a_dom_cloning(self):
        for source, status in [('const x = element.cloneNode();', 1), ('const x = element.cloneNode(true);', 1),
                               ('const x = element["cloneNode"]();', 1),
                               ('const x = element.other(); // cloneNode()', 0)]:
            with self.subTest(source=source):
                self.write('test.ts', source)
                self.write('test.tsx', source)
                self.scan('ast', status)

    def test_t3797a_style_overrides(self):
        for source, status in [
            ('const css = "color: red !important";', 1),
            ('const css = `a {\n color:\n red !important;\n}`;', 1),
            ('const view = <div style={{color: "red !important"}} />;', 1),
            ('const text = "This is !important prose"; // color: red !important', 0),
            ('const text = "Note: this is !important prose";', 0),
            ('const text = "Note: this is !important";', 0),
            ('const css = `margin-top: 0 !important /* legacy */;`;', 1),
            ('const view = <div style={{"margin-top": "0 !important"}} />;', 1),
        ]:
            with self.subTest(source=source):
                self.write('test.tsx', source)
                self.scan('ast', status)

    def test_t3797a_ast_extra_beside_exception(self):
        for rule, path, source in [('sleep-poll', 'a.rs', 'fn f() { loop { sleep(x); } }\n'),
                                   ('dom-clone', 'a.ts', 'element.cloneNode();\n'),
                                   ('style-override', 'a.tsx', 'const a = "color: red !important";\n')]:
            with self.subTest(rule=rule):
                self.write(path, source)
                self.baseline('ast')
                self.scan('ast', 0)
                self.write(path, source * 2)
                self.assertIn(rule, self.scan('ast', 1))
                self.write(path, source)

    def test_t3797a_spelling(self):
        self.write('text.txt', 'the spelling is correct\n')
        self.scan('typos', 0)
        self.write('text.txt', 't' + 'eh spelling\n')
        self.baseline('typos')
        self.scan('typos', 0)
        self.write('text.txt', ('t' + 'eh spelling\n') * 2)
        self.assertIn('text.txt', self.scan('typos', 1))

    def test_t3797a_python(self):
        self.write('loop/a_test.py', 'print("correct")\n')
        self.scan('ruff', 0)
        self.write('loop/a_test.py', 'import os\n')
        self.baseline('ruff')
        self.scan('ruff', 0)
        self.write('loop/a_test.py', 'import os\nimport sys\n')
        self.assertIn('F401', self.scan('ruff', 1))

    def test_t3797a_baseline_ratchet(self):
        self.write('big', 'x\n' * 1002)
        debt = self.baseline('size')
        self.scan('size', 0)
        self.write('big', 'x\n' * 1001)
        self.assertIn('shrink ceiling', self.scan('size', 1))
        debt['size'][0]['ceiling'] = 1001
        self.write('tools/lint/debt.json', json.dumps(debt))
        self.scan('size', 0)
        debt['size'][0]['ceiling'] = 1003
        self.write('tools/lint/debt.json', json.dumps(debt))
        self.assertIn('raised size ceiling', self.scan('size', 1))
        debt['size'] = [{'path': 'new', 'ceiling': 1001, 'reason': 'Unapproved'}]
        self.write('tools/lint/debt.json', json.dumps(debt))
        self.assertIn('merge-base: new exception', self.scan('size', 1))
        debt['size'] = []
        self.write('tools/lint/debt.json', json.dumps(debt))
        self.write('big', 'x\n' * 1000)
        self.scan('size', 0)

    def test_t3797a_baseline_ratchet_stale(self):
        self.write('loop/a.py', 'import os\n')
        self.baseline('ruff')
        self.write('loop/a.py', '')
        self.assertIn('stale exception', self.scan('ruff', 1))

    def test_t3797a_baseline_ratchet_initial_base(self):
        self.write('tools/lint/debt.json', json.dumps(EMPTY))
        self.git('rm', 'tools/lint/debt.json')
        self.write('loop/a.py', 'import os\n')
        self.commit()
        self.write('tools/lint/debt.json', json.dumps(EMPTY))
        self.baseline('ruff')
        # Exercise bootstrap against the commit without any baseline, not this new fixture commit.
        base = self.git('rev-parse', 'HEAD^').strip()
        self.scan('ruff', 0, '--base', base)
        self.write('loop/a.py', 'import os\nimport sys\n')
        output = self.scan('ruff', 0, '--record')
        debt = json.loads((self.root / 'tools/lint/debt.json').read_text())
        debt['ruff'] = [dict(row, reason='Unapproved') for row in json.JSONDecoder().raw_decode(output)[0]['ruff']]
        self.write('tools/lint/debt.json', json.dumps(debt))
        self.assertIn('merge-base', self.scan('ruff', 1, '--base', base))

    def test_t3797a_lint_failures(self):
        self.write('tools/lint/debt.json', '{')
        self.assertIn('failure', self.scan('size', 2))
        self.write('loop/broken.py', 'def :\n')
        self.write('tools/lint/debt.json', json.dumps(EMPTY))
        self.assertIn('invalid-syntax', self.scan('ruff', 1))

    def cargo(self, license='MIT', dependencies=''):
        self.write('Cargo.toml', '[package]\nname="fixture"\nversion="0.1.0"\nedition="2024"\nlicense="' + license + '"\n' + dependencies)
        self.write('src/lib.rs', 'pub fn fixture() {}\n')
        subprocess.run(['cargo', 'generate-lockfile'], cwd=self.root, check=True, capture_output=True)

    def test_t3797a_dependency_policy_licenses(self):
        for license, status in [('MIT OR Apache-2.0', 0), ('GPL-3.0-only', 1)]:
            with self.subTest(license=license):
                self.cargo(license)
                self.scan('dependencies', status)

    def test_t3797a_dependency_policy_duplicate_versions(self):
        self.cargo(dependencies='[dependencies]\nold={package="itoa",version="=0.4.8"}\n'
                   + '[target.\'cfg(target_os = "macos")\'.dependencies]\nnew={package="itoa",version="=1.0.15"}\n')
        self.assertIn('itoa', self.scan('dependencies', 1))
        debt = self.baseline('dependencies')
        self.scan('dependencies', 0)
        self.assertEqual({row['version'] for row in debt['dependencies'] if row['rule'] == 'duplicate'}, {'0.4.8', '1.0.15'})
        self.cargo(dependencies='[dependencies]\nold={package="itoa",version="=0.4.8"}\nnew={package="itoa",version="=1.0.15"}\nextra={package="itoa",version="=0.3.4"}\n')
        self.assertIn('0.3.4', self.scan('dependencies', 1))

    def test_t3797a_dependency_policy_advisories(self):
        self.cargo(dependencies='[dependencies]\ntokio="=1.53.1"\n')
        self.assertIn('RUSTSEC-2026-0386', self.scan('dependencies', 1))
        self.baseline('dependencies')
        self.scan('dependencies', 0)

    def test_t3797a_lint_failures_missing_tool(self):
        isolated = self.root / 'isolated'
        isolated.mkdir()
        shutil.copyfile(HERE / 'scan.py', isolated / 'scan.py')
        result = subprocess.run([sys.executable, isolated / 'scan.py', 'ruff', '--root', self.root], capture_output=True, text=True)
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
        self.assertIn('ruff', result.stderr)

    def test_t3797a_lint_failures_graph(self):
        self.write('Cargo.toml', '[not valid')
        self.assertIn('cargo', self.scan('dependencies', 2))


if __name__ == '__main__':
    unittest.main()
